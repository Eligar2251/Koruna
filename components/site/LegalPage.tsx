import { Footer } from "../chrome/Footer";
import { readSettings } from "../../lib/settings";
import { defaultSettings } from "../../lib/site-config";
export async function LegalPage({
  kind,
}: {
  kind: "privacy" | "consent" | "cookies";
}) {
  const settings = await readSettings().catch(() => defaultSettings),
    f = settings.fields;
  return (
    <div id="allrecords" className="t-records">
      <main className="csb-policy">
        <a href="/">← На главную</a>
        <h1>
          {kind === "privacy"
            ? "Политика обработки персональных данных"
            : kind === "consent"
              ? "Согласие на обработку персональных данных"
              : "Cookie и локальное хранилище"}
        </h1>
        <p>Редакция: {f.policyDate}</p>
        {!settings.privacyReady && (
          <p className="draft">
            Сведения в документе уточняются оператором. Юридическая готовность и
            выполнение требований к локализации данных не подтверждены.
            {settings.requestsEnabled
              ? " Приём заявок включён; при отправке требуется отдельное согласие."
              : " Приём заявок временно приостановлен; для связи используйте телефон."}
          </p>
        )}
        {kind === "cookies" ? (
          <>
            <h2>Только необходимые технологии</h2>
            <p>
              Сайт не подключает стороннюю аналитику, рекламу, пиксели и внешние
              карты. Файлы cookie csb_access и csb_refresh нужны для входа
              администратора (до 12 часов); они HttpOnly и SameSite=Strict.
              Корзина csb-cart хранится только в localStorage вашего браузера,
              пока вы не очистите её. Выбор cookie-уведомления csb-cookie-notice
              и разрешение уведомлений панели csb-notifications также хранятся
              локально до удаления данных браузера. Эти данные не используются
              для рекламного профилирования.
            </p>
            <h2>Управление</h2>
            <p>
              Можно удалить данные в настройках браузера. Это очистит корзину и
              завершит вход. Повторно открыть уведомление можно кнопкой
              «Настройки cookie» в подвале. Отдельные разрешения на
              необязательные cookie не запрашиваются: такие технологии не
              установлены. При их добавлении оператор должен обновить документы
              и реализовать предварительное согласие.
            </p>
            <a href="/privacy">Политика обработки персональных данных</a>
          </>
        ) : (
          <>
            <h2>1. Оператор</h2>
            <p>
              {f.legalFull}, ИНН {f.inn}, ОГРН/ОГРНИП {f.ogrn}
              {f.kpp ? `, КПП ${f.kpp}` : ""}. Юридический адрес:{" "}
              {f.legalAddress || "не заполнен оператором"}. Для обращений о
              персональных данных: {f.privacyEmail}.
            </p>
            <h2>2. Цели, данные и правовые основания</h2>
            <p>
              {kind === "consent"
                ? "Я свободно, своей волей и в своём интересе даю оператору отдельное согласие на обработку предоставленных мной данных: имени, телефона, необязательной электронной почты, адреса доставки и текста обращения. Согласие не является частью согласия с другими документами и не распространяется на рекламные рассылки."
                : "Обрабатываются данные, которые посетитель сам указывает в заявке или заказе: имя, телефон, необязательная электронная почта, адрес доставки и текст обращения. Цели — ответ на вопрос о цене/наличии, согласование поставки и доставки, подготовка и исполнение заказа. Основания — отдельное согласие субъекта и, когда применимо, заключение и исполнение договора по инициативе субъекта, требования закона."}
            </p>
            <h2>3. Действия с данными и получатели</h2>
            <p>
              Сбор, запись, систематизация, накопление, хранение, уточнение,
              извлечение, использование, предоставление уполномоченным
              обработчикам только в заявленных целях, блокирование, удаление и
              уничтожение; с использованием средств автоматизации и без них.
              Общедоступное распространение данных не производится. Не
              указывайте специальные категории данных или сведения о третьих
              лицах в комментариях.
            </p>
            <p>
              Обработчики и места обработки:{" "}
              {f.processors ||
                "сведения заполняются оператором до запуска форм"}
              .
            </p>
            <h2>4. Хранение и срок</h2>
            <p>
              Первичная запись и хранение персональных данных граждан РФ:{" "}
              {f.storageLocation || "место хранения не подтверждено оператором"}
              . Оператор обязан обеспечить предусмотренную законом локализацию
              баз данных в РФ. Подключение внешнего сервиса само по себе не
              подтверждает выполнение этого требования. Трансграничная передача
              допускается только при наличии установленных законом оснований и
              выполнении применимых требований.
            </p>
            <p>
              Срок хранения и основание:{" "}
              {f.retention || "срок заполняется оператором до запуска форм"}. По
              достижении целей или отзыве согласия данные
              удаляются/обезличиваются в установленные законом сроки, кроме
              данных, для которых требуется иное законное основание хранения.
              Отметка согласия, версия документа и время сохраняются вместе с
              обращением.
            </p>
            <h2>5. Права и отзыв согласия</h2>
            <p>
              Субъект вправе получить сведения об обработке, потребовать
              уточнения, блокирования или уничтожения данных, отозвать согласие,
              обжаловать действия оператора в Роскомнадзоре или суде. Для
              обращения напишите на {f.privacyEmail}, указав данные, позволяющие
              найти обращение и подтвердить личность без избыточных сведений.
              Оператор отвечает в сроки, предусмотренные законом. Отзыв согласия
              не влияет на правомерность предшествующей обработки и не исключает
              обработку на других законных основаниях.
            </p>
            <h2>6. Защита и документы</h2>
            <p>
              Доступ к заявкам предоставляется авторизованным администраторам.
              Оператор обеспечивает организационные и технические меры защиты,
              контроль доступа, сроки удаления и реагирование на инциденты.
              Данные не передаются в текстах браузерных уведомлений. Технические
              журналы хостинга регулируются договором оператора с его
              провайдером; их состав, расположение и сроки должны быть учтены
              оператором.
            </p>
            <p>
              <a href="/cookies">Cookie и локальное хранилище</a> ·{" "}
              <a href={kind === "consent" ? "/privacy" : "/soglasie"}>
                {kind === "consent"
                  ? "Политика обработки данных"
                  : "Текст отдельного согласия"}
              </a>
            </p>
          </>
        )}
      </main>
      <Footer />
    </div>
  );
}
